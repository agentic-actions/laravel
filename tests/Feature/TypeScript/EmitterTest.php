it('maps every schema shape, an empty input and output as Record<string, never>, with Json declared once', function () {
    $this->mountRoutes(function (): void {
        $this->generatedRoute(EveryShape::class);
        $this->generatedRoute(CreateNote::class);
        $this->generatedRoute(ListNotes::class);
    });

    $file = app(Emitter::class)->render();

    expect($file)
        ->toStartWith(<<<'TS'
            // Generated by `php artisan actions:typescript` from agentic-actions/laravel 0.1.0. Do not edit.
            import { action, type ActionDefinition } from '@agentic-actions/client';

            type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

            export type CreateNoteInput = {
            TS)
        ->toContain(<<<'TS'
            export type EveryShapeInput = {
                status: 'draft' | 'published';
                priority: 1 | 2 | 3;
                ratio?: number;
                flag: boolean;
                tags: Array<string>;
                labels?: Array<'a' | 'b'>;
                anything?: Array<Json>;
                meta?: Record<string, Json>;
                author: {
                    /** As printed on the byline. */
                    name: string;
                    email?: string | null;
                };
                lines?: Array<{
                    sku: string;
                    qty?: number;
                }>;
                attachment?: File | Blob;
                'content-type'?: string;
                note: string | null;
            };
            TS)
        ->toContain(<<<'TS'
            /** Every schema shape the emitter maps. It keeps *\/ inside the comment. */
            export const everyShape = (): ActionDefinition<EveryShapeInput, EveryShapeOutput> =>
                action({ name: 'every-shape', method: 'post', url: '/every-shape', touches: ['shapes', 'it\'s'] });
            TS)
        ->toContain('export type EveryShapeOutput = Record<string, never>;')
        ->toContain('export type ListNotesInput = Record<string, never>;')
        ->toContain(<<<'TS'
            export type ListNotesOutput = {
                posts: Array<{
                    id: number;
                    title: string;
                }>;
            };
            TS)
        ->and(substr_count($file, 'type Json ='))->toBe(1)
        ->and($file)->not->toMatch('/\\bany\\b|\\bunknown\\b/');
});

