it('writes the golden file exactly for CreatePost mounted on the web and api. groups', function () {
    $this->mountRoutes(function (): void {
        // The api mount is registered first, so the web mount wins by its middleware, not by its order.
        Route::middleware(['api', 'auth:sanctum'])->prefix('api/actions')->name('api.actions.')
            ->group(fn () => $this->generatedRoute(CreatePost::class));
        Route::middleware(['web', 'auth'])->prefix('actions')->name('actions.')
            ->group(fn () => $this->generatedRoute(CreatePost::class));
    });

    $file = app(Emitter::class)->render();

    expect($file)->toBe(file_get_contents(__DIR__.'/__snapshots__/create-post.ts'))
        ->and($file)->not->toContain('/api/actions/create-post');
});

it('stamps the version Packages reports, without a leading v', function () {
    $this->mountRoutes(fn () => $this->generatedRoute(CreatePost::class));

    expect(app(Emitter::class)->render())->toStartWith('// Generated by `php artisan actions:typescript` from agentic-actions/laravel 0.1.0. Do not edit.');

