it('takes route parameters out of the input and fills them with uri()', function () {
    $this->mountRoutes(function (): void {
        Route::middleware('web')->prefix('teams/{team}/actions')->name('teams.actions.')
            ->group(fn () => $this->generatedRoute(TeamNote::class));
        Route::post('posts/{post}/archive', ArchivePost::class)->name('posts.archive');
    });

    $file = app(Emitter::class)->render();

    expect($file)
        ->toContain("import { action, uri, type ActionDefinition } from '@agentic-actions/client';")
        ->toContain(<<<'TS'
            export type TeamNoteParams = { team: string | number };

            export type TeamNoteInput = {
                title: string;
            };

            export type TeamNoteOutput = Record<string, never>;

            /** Create a note in the current team. */
            export const teamNote = (params: TeamNoteParams): ActionDefinition<TeamNoteInput, TeamNoteOutput> =>
                action({ name: 'team-note', method: 'post', url: uri('/teams/{team}/actions/team-note', params), touches: [] });
            TS)
        ->toContain(<<<'TS'
            export type ArchivePostParams = { post: string | number };

            export type ArchivePostInput = {
                reason?: string;
            };
            TS)
        ->toContain("url: uri('/posts/{post}/archive', params)");
});

it('marks an optional route parameter optional', function () {
