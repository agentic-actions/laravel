it('renders the same text twice, whatever order the routes were registered in', function () {
    $mount = function (array $classes): string {
        Route::setRoutes(new RouteCollection);

        $this->mountRoutes(function () use ($classes): void {
            foreach ($classes as $class) {
                $this->generatedRoute($class);
            }
        });

        return app(Emitter::class)->render();
    };

    $first = $mount([CreateNote::class, ListNotes::class, EveryShape::class]);

    expect($mount([EveryShape::class, ListNotes::class, CreateNote::class]))->toBe($first)
        ->and(app(Emitter::class)->render())->toBe($first);
});

it('refuses an export name TypeScript cannot use, strict mode\'s included', function (?string $route, string $message) {
    $this->mountRoutes(function () use ($route): void {
        if ($route === null) {
            $this->generatedRoute(EvalAction::class);

            return;
        }

        Route::post('notes', CreateNote::class)->name('notes.store');
        Route::post('notes/extra', CreateNote::class)->name($route);
    });

    expect(fn () => app(Emitter::class)->render())->toThrow(LogicException::class, $message);
})->with([
    'a reserved word' => ['delete', 'The route [delete] cannot be exported to TypeScript as [delete]. Give it another name.'],
    'the route eval' => ['eval', 'The route [eval] cannot be exported to TypeScript as [eval]. Give it another name.'],
    'the route arguments' => ['arguments', 'The route [arguments] cannot be exported to TypeScript as [arguments]. Give it another name.'],
    'the action eval' => [null, 'The action [eval] cannot be exported to TypeScript as [eval]. Give it another name.'],
]);

it('refuses two exports with one name', function () {
    $this->mountRoutes(function (): void {
        $this->generatedRoute(CreateNote::class);
        Route::post('notes', CreateNote::class)->name('create-note');
    });

    app(Emitter::class)->render();
})->throws(LogicException::class, 'The route [create-note] is exported to TypeScript as [createNote], a name the action [create-note] already takes.');

