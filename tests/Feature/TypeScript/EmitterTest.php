it('writes js/tests/fixtures/actions.ts from the fixture routes, and fails when the committed copy is stale', function () {
    $this->mountRoutes(function (): void {
        Route::middleware(['api', 'auth:sanctum'])->prefix('api/actions')->name('api.actions.')
            ->group(fn () => $this->generatedRoute(CreateNote::class));

        Route::middleware(['web', 'auth'])->prefix('actions')->name('actions.')->group(function (): void {
            $this->generatedRoute(CreateNote::class);
            $this->generatedRoute(ListNotes::class);
            $this->generatedRoute(EveryShape::class);
        });

        Route::middleware(['web', 'auth'])->prefix('teams/{team}/actions')->name('teams.actions.')
            ->group(fn () => $this->generatedRoute(TeamNote::class));

        Route::middleware(['web', 'auth'])->group(function (): void {
            Route::post('posts/{post}/archive', ArchivePost::class)->name('posts.archive');
            Route::post('api/posts/{post}/archive/{mode?}', ArchivePost::class)->name('api.posts.archive');
        });
    });

    $path = dirname(__DIR__, 3).'/js/tests/fixtures/actions.ts';
    $rendered = app(Emitter::class)->render();
    $committed = is_file($path) ? file_get_contents($path) : null;

    if ($committed !== $rendered) {
        File::ensureDirectoryExists(dirname($path));
        File::put($path, $rendered);
    }

    expect($committed)->toBe($rendered, 'js/tests/fixtures/actions.ts was stale and has been rewritten: run npm --prefix js run test:types, then commit it.');
});
