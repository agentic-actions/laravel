it('exports named hand-written routes as extras, by route name', function () {
    $this->mountRoutes(function (): void {
        Route::middleware('web')->group(function (): void {
            Route::post('notes/unnamed', CreateNote::class);
            $this->generatedRoute(CreateNote::class);
            Route::post('notes', CreateNote::class)->name('notes.store');
        });
        Route::post('posts/{post}/archive', ArchivePost::class)->name('posts.archive');
        Route::post('api/posts/{post}/archive', ArchivePost::class)->name('api.posts.archive');
    });

    $file = app(Emitter::class)->render();

    expect($file)
        ->toContain(<<<'TS'
            /** Create a note for the signed-in author. */
            export const createNote = (): ActionDefinition<CreateNoteInput, CreateNoteOutput> =>
                action({ name: 'create-note', method: 'post', url: '/create-note', touches: [] });
            TS)
        ->toContain(<<<'TS'
            /** Create a note for the signed-in author. */
            export const notesStore = (): ActionDefinition<NotesStoreInput, NotesStoreOutput> =>
                action({ name: 'create-note', method: 'post', url: '/notes', touches: [] });
            TS)
        ->toContain("export const archivePost = (params: ArchivePostParams): ActionDefinition<ArchivePostInput, ArchivePostOutput> =>\n    action({ name: 'archive-post', method: 'post', url: uri('/posts/{post}/archive', params), touches: [] });")
        ->toContain("export const apiPostsArchive = (params: ApiPostsArchiveParams): ActionDefinition<ApiPostsArchiveInput, ApiPostsArchiveOutput> =>\n    action({ name: 'archive-post', method: 'post', url: uri('/api/posts/{post}/archive', params), touches: [] });")
        ->not->toContain('notes/unnamed');

    // In action-name order, each primary before its extras.
    expect(strpos($file, 'export const apiPostsArchive'))->toBeGreaterThan(strpos($file, 'export const archivePost'))
        ->and(strpos($file, 'export const createNote'))->toBeGreaterThan(strpos($file, 'export const apiPostsArchive'))
        ->and(strpos($file, 'export const notesStore'))->toBeGreaterThan(strpos($file, 'export const createNote'));
});

